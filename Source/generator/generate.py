#!/usr/bin/env python3
"""Generate a core from a configuration.

    python Source/generator/generate.py Source/generator/configs/rv64i-m.toml
    python Source/generator/generate.py <config.toml> --out build/<name>

Writes build/<name>/generated/: the core's configuration header, the core
and testbench (instantiated from templates/), the HLS configuration, and the
DoomV arguments that describe the same machine (doomv.args) -- so the core
and its reference come from one configuration and cannot disagree about what
machine they are.

The output is never edited by hand (docs/decisions.md, 2026-10-21): to
change a core, change a template, this script or the configuration, and
generate again.

Only option values the templates implement are accepted. An option value is
added when its generated core passes the lock-step against DoomV
(docs/configurator.md).
"""
from __future__ import annotations

import argparse
import shutil
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TEMPLATES = HERE / "templates"

# What the templates implement today, per option.
SUPPORTED = {
    "isa": {"rv64i"},
    "extensions": {"zicsr", "zifencei"},
    "priv": {"m"},
    "pipeline": {"inorder5"},
    "branch_predictor": {"static_not_taken"},
    "misaligned": {"trap"},
    "pmp_entries": {0},
    "memory.kind": {"bram"},
}

NOTICE = """\
GENERATED by Ouroboros (Source/generator/generate.py) from {config}.

Do not edit anything here. A wrong output is a generator bug: fix the
template or the generator, and generate again (docs/decisions.md,
2026-10-21).
"""


class ConfigError(ValueError):
    pass


def check(cfg: dict) -> dict:
    core, clock, mem, target = cfg["core"], cfg["clock"], cfg["memory"], cfg["target"]
    for key in ("isa", "priv", "pipeline", "branch_predictor", "misaligned", "pmp_entries"):
        if core[key] not in SUPPORTED[key]:
            raise ConfigError(f"core.{key} = {core[key]!r}: the generator implements {sorted(map(str, SUPPORTED[key]))}")
    for e in core.get("extensions", []):
        if e not in SUPPORTED["extensions"]:
            raise ConfigError(f"extension {e!r}: the generator implements {sorted(SUPPORTED['extensions'])}")
    if "zicsr" not in core.get("extensions", []):
        raise ConfigError("Zicsr is required: machine mode needs its CSRs")
    if mem["kind"] not in SUPPORTED["memory.kind"]:
        raise ConfigError(f"memory.kind = {mem['kind']!r}: the generator implements {sorted(SUPPORTED['memory.kind'])}")
    if mem["kib"] <= 0 or mem["kib"] & (mem["kib"] - 1):
        raise ConfigError("memory.kib must be a power of two")
    hz = clock["core_mhz"] * 1_000_000
    if hz % clock["timebase_hz"]:
        raise ConfigError("clock.core_mhz must be a whole multiple of clock.timebase_hz")
    return {
        "name": core["name"],
        "isa": core["isa"],
        "extensions": core.get("extensions", []),
        "priv": core["priv"],
        "misaligned_trap": core["misaligned"] == "trap",
        "pmp_entries": core["pmp_entries"],
        "cycles_per_tick": hz // clock["timebase_hz"],
        "clock_ns": 1000.0 / clock["core_mhz"],
        "mem_base": mem["base"],
        "mem_words": mem["kib"] * 1024 // 8,
        "part": target["part"],
    }


def misa(c: dict) -> int:
    v = 2 << 62                              # MXL: 64-bit
    for letter in c["isa"][4:]:
        v |= 1 << (ord(letter.upper()) - ord("A"))
    if "s" in c["priv"]:
        v |= 1 << (ord("S") - ord("A"))
    if "u" in c["priv"]:
        v |= 1 << (ord("U") - ord("A"))
    return v


def config_header(c: dict, source: str) -> str:
    return f"""#pragma once
// {NOTICE.format(config=source).strip().replace(chr(10), chr(10) + '// ')}
//
// The core's parameters: everything the templates choose at compile time.

namespace cfg {{
constexpr unsigned long long MEM_BASE = {c['mem_base']:#x}ull;
constexpr unsigned MEM_WORDS = {c['mem_words']};           // 8-byte words of test memory
constexpr unsigned long long MISA = {misa(c):#x}ull;
constexpr bool MISALIGNED_TRAP = {str(c['misaligned_trap']).lower()};
constexpr unsigned PMP_ENTRIES = {c['pmp_entries']};
constexpr unsigned long long CYCLES_PER_TICK = {c['cycles_per_tick']}ull;   // core cycles per mtime tick
}} // namespace cfg
"""


def doomv_args(c: dict) -> list[str]:
    march = c["isa"] + "".join("_" + e for e in c["extensions"])
    return [f"-march={march}", f"-priv={c['priv']}", f"-pmp={c['pmp_entries']}",
            "-misaligned=" + ("trap" if c["misaligned_trap"] else "split"),
            f"-cycle-clock={c['cycles_per_tick']}"]


def generate(config: Path, out: Path) -> Path:
    raw = tomllib.loads(config.read_text())
    c = check(raw)
    gen = out / "generated"
    if gen.exists():
        shutil.rmtree(gen)
    gen.mkdir(parents=True)
    try:
        source = str(config.resolve().relative_to(ROOT)).replace("\\", "/")
    except ValueError:
        source = str(config)
    (gen / "GENERATED.txt").write_text(NOTICE.format(config=source))
    (gen / "config.toml").write_text(config.read_text())
    (gen / "config.hpp").write_text(config_header(c, source))
    for t in sorted((TEMPLATES / "core").iterdir()) + sorted((TEMPLATES / "tb").iterdir()):
        text = t.read_text()
        (gen / t.name).write_text(f"// {NOTICE.format(config=source).strip().splitlines()[0]} Do not edit.\n" + text)
    (gen / "hls_config.cfg").write_text(f"""# {NOTICE.format(config=source).strip().splitlines()[0]}
part={c['part']}

[hls]
syn.file=core.cpp
syn.top=core_top
tb.file=core_tb.cpp
clock={c['clock_ns']:.3f}ns
""")
    (gen / "doomv.args").write_text(" ".join(doomv_args(c)) + "\n")
    return gen


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path)
    ap.add_argument("--out", type=Path, help="the build folder (default build/<name>)")
    args = ap.parse_args()
    try:
        name = tomllib.loads(args.config.read_text())["core"]["name"]
        gen = generate(args.config, args.out or ROOT / "build" / name)
    except (ConfigError, KeyError) as e:
        print(f"configuration: {e}", file=sys.stderr)
        return 1
    print(f"generated {gen}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
